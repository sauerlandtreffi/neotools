function glyph(ch: string): string[] {
  return GLYPH[ch] ?? GLYPH[ch.toUpperCase()] ?? GLYPH['?'] ?? ['1'];
}

export function measureBitmap(text: string, scale: number): { width: number; height: number } {
  let w = 0;
  for (const ch of text) {
    const g = glyph(ch)!;
    w += ((g[0]?.length ?? 1) + 1) * scale;
  }
  return { width: Math.max(1, w), height: 8 * scale };
}

export function stampBitmap(
  dest: Uint8ClampedArray,
  dw: number,
  dh: number,
  text: string,
  x: number,
  y: number,
  scale: number,
  rgba: readonly [number, number, number, number],
): void {
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text) {
    const g = glyph(ch)!;
    const gw = g[0]?.length ?? 1;
    for (let gy = 0; gy < g.length; gy++) {
      const row = g[gy] ?? '';
      for (let gx = 0; gx < row.length; gx++) {
        if (row[gx] !== '1') continue;
        for (let oy = 0; oy < scale; oy++) {
          for (let ox = 0; ox < scale; ox++) {
            const px = cx + gx * scale + ox;
            const py = cy + gy * scale + oy;
            if (px < 0 || py < 0 || px >= dw || py >= dh) continue;
            const i = (py * dw + px) * 4;
            const a = (rgba[3] ?? 255) / 255;
            dest[i] = Math.round((dest[i] ?? 0) * (1 - a) + rgba[0] * a);
            dest[i + 1] = Math.round((dest[i + 1] ?? 0) * (1 - a) + rgba[1] * a);
            dest[i + 2] = Math.round((dest[i + 2] ?? 0) * (1 - a) + rgba[2] * a);
            dest[i + 3] = 255;
          }
        }
      }
    }
    cx += (gw + 1) * scale;
  }
}
