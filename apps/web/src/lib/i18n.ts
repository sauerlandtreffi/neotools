export function switchLocalePath(path: string, from: Locale): string {
  const clean = path.replace(/\/$/, '') || '/';
  if (SWITCH[clean]) return SWITCH[clean];
  if (from === 'de') return clean === '/' ? '/en' : `/en${clean}`;
  return clean.replace(/^\/en/, '') || '/';
}

/** Canonical de/en URLs for hreflang, including aliased routes like /verlauf ↔ /en/history. */
export function hreflangUrls(locale: Locale, path: string): { de: string; en: string } {
  const current = localePath(locale, path);
  const other = switchLocalePath(current, locale);
  return locale === 'de' ? { de: current, en: other } : { de: other, en: current };
}

